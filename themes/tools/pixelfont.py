PX, ADV, UPM, ASC, DESC = 128, 6 * 128, 1024, 7 * 128, 2 * 128   # 8 px em; baseline under row 6


def rects(rows):
    out = []
    for r, line in enumerate(rows):
        c = 0
        while c < len(line):
            if line[c] == '#':
                s = c
                while c < len(line) and line[c] == '#':
                    c += 1
                y1 = (6 - r) * PX  # row 6 sits on the baseline
                out.append((s * PX + PX // 2, y1, c * PX + PX // 2, y1 + PX))
            else:
                c += 1
    return out


def glyf_entry(rs, round_=False):
    if not rs:
        return b''
    pts, ends = [], []  # (x, y, on-curve)
    for x0, y0, x1, y1 in rs:  # clockwise: TrueType outer contours
        if round_:  # a pill: quarter circles (quadratic, the corner as the off-curve point) at both ends
            r = (y1 - y0) // 2
            pts += [(x0 + r, y0, 1), (x0, y0, 0), (x0, y0 + r, 1), (x0, y1, 0), (x0 + r, y1, 1),
                    (x1 - r, y1, 1), (x1, y1, 0), (x1, y1 - r, 1), (x1, y0, 0), (x1 - r, y0, 1)]
        else:
            pts += [(x0, y0, 1), (x0, y1, 1), (x1, y1, 1), (x1, y0, 1)]
        ends.append(len(pts) - 1)
    xs, ys = [p[0] for p in pts], [p[1] for p in pts]
    b = struct.pack('>hhhhh', len(rs), min(xs), min(ys), max(xs), max(ys))
    b += struct.pack(f'>{len(ends)}H', *ends) + struct.pack('>H', 0) + bytes(p[2] for p in pts)
    px = py = 0
    dx, dy = [], []
    for x, y, _ in pts:
        dx.append(x - px); dy.append(y - py); px, py = x, y
    b += struct.pack(f'>{len(dx)}h', *dx) + struct.pack(f'>{len(dy)}h', *dy)
    return b + b'\0' * (-len(b) % 4)


def checksum(data):
    data += b'\0' * (-len(data) % 4)
    return sum(struct.unpack(f'>{len(data) // 4}I', data)) & 0xFFFFFFFF


def name_table(family):
    recs = {0: 'Made for Voltage, CC0 1.0 (public domain)', 1: family, 2: 'Regular', 3: f'{family} Regular 1.0', 4: family,
            5: 'Version 1.0', 6: family.replace(' ', '')}
    strs, entries, off = b'', [], 0
    for nid, s in recs.items():
        e = s.encode('utf-16-be')
        entries.append(struct.pack('>HHHHHH', 3, 1, 0x409, nid, len(e), off))
        strs += e; off += len(e)
    return struct.pack('>HHH', 0, len(entries), 6 + 12 * len(entries)) + b''.join(entries) + strs


def cmap_table(chars):  # format 4, one segment per character + the 0xFFFF end
    segs = [(ord(ch), gid) for gid, ch in chars] + [(0xFFFF, 0)]
    n = len(segs)
    ends = [c for c, _ in segs]
    deltas = [((g - c) & 0xFFFF) if c != 0xFFFF else 1 for c, g in segs]
    sr = 2 * (1 << (n.bit_length() - 1)); es = (n.bit_length() - 1)
    sub = struct.pack('>HHHHHHH', 4, 0, 0, n * 2, sr, es, n * 2 - sr)
    sub += struct.pack(f'>{n}H', *ends) + b'\0\0' + struct.pack(f'>{n}H', *ends) + struct.pack(f'>{n}H', *deltas) + struct.pack(f'>{n}H', *([0] * n))
    sub = sub[:2] + struct.pack('>H', len(sub)) + sub[4:]
    return struct.pack('>HHHHI', 0, 1, 3, 1, 12) + sub


def build(out, family='Volt Pixel', round_=False):
    chars = sorted(G.items(), key=lambda kv: ord(kv[0]))
    order = [(i + 1, ch) for i, (ch, _) in enumerate(chars)]
    glyphs = [glyf_entry([(PX, 0, 5 * PX, PX), (PX, PX, 2 * PX, 7 * PX)])]  # .notdef: an L
    glyphs += [glyf_entry(rects(rows), round_) for _, rows in chars]
    glyf, loca = b'', []
    for g in glyphs:
        loca.append(len(glyf)); glyf += g
    loca.append(len(glyf))
    ng = len(glyphs)
    allr = [r for _, rows in chars for r in rects(rows)]
    xmin, ymin = min(r[0] for r in allr), min(r[1] for r in allr)
    xmax, ymax = max(r[2] for r in allr), max(r[3] for r in allr)
    t = {}
    t[b'head'] = struct.pack('>IIIIHHqqhhhhHHhhh', 0x00010000, 0x00010000, 0, 0x5F0F3CF5, 0x000B, UPM, 0, 0, xmin, ymin, xmax, ymax, 0, 8, 2, 1, 0)
    t[b'hhea'] = struct.pack('>IhhhHhhhhhhhhhhhH', 0x00010000, ASC, -DESC, 0, ADV, 0, 0, ADV, 1, 0, 0, 0, 0, 0, 0, 0, ng)
    mc = max(len(rects(rows)) for _, rows in chars)
    t[b'maxp'] = struct.pack('>IHHHHHHHHHHHHHH', 0x00010000, ng, (10 if round_ else 4) * mc, mc, 0, 0, 2, 0, 0, 0, 0, 0, 0, 0, 0)
    os2 = struct.pack('>HhHHHhhhhhhhhhhh', 4, ADV, 400, 5, 0, 512, 512, 0, 128, 512, 512, 0, 384, 64, 400, 0)
    os2 += bytes(10) + struct.pack('>IIII', 3, 0, 0, 0) + b'VOLT' + struct.pack('>HHH', 0x40, 0x20, max(ord(c) for c in G))
    os2 += struct.pack('>hhhHH', ASC, -DESC, 0, ASC + 128, DESC) + struct.pack('>II', 1, 0) + struct.pack('>hhHHH', 5 * PX, 7 * PX, 0, 32, 0)
    t[b'OS/2'] = os2
    t[b'hmtx'] = b''.join(struct.pack('>Hh', ADV, PX // 2) for _ in range(ng))
    t[b'cmap'] = cmap_table(order)
    t[b'loca'] = struct.pack(f'>{len(loca)}I', *loca)
    t[b'glyf'] = glyf
    t[b'name'] = name_table(family)
    t[b'post'] = struct.pack('>IIhhIIIII', 0x00030000, 0, -PX, PX // 2, 1, 0, 0, 0, 0)
    tags = sorted(t)
    n = len(tags); es = n.bit_length() - 1; sr = 16 * (1 << es)
    head = struct.pack('>IHHHH', 0x00010000, n, sr, es, n * 16 - sr)
    off = 12 + 16 * n
    dirs, body = b'', b''
    for tag in tags:
        d = t[tag]
        dirs += struct.pack('>4sIII', tag, checksum(d), off + len(body), len(d))
        body += d + b'\0' * (-len(d) % 4)
    font = bytearray(head + dirs + body)
    adj = (0xB1B0AFBA - checksum(bytes(font))) & 0xFFFFFFFF
    hoff = struct.unpack('>I', dirs[tags.index(b'head') * 16 + 8: tags.index(b'head') * 16 + 12])[0]
    font[hoff + 8: hoff + 12] = struct.pack('>I', adj)
    open(out, 'wb').write(bytes(font))
    print(out, len(font), 'bytes,', ng, 'glyphs')


if __name__ == '__main__':
    build(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else 'Volt Pixel', '--round' in sys.argv)
